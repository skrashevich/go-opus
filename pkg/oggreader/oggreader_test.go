package oggreader_test

import (
	"bytes"
	"errors"
	"io"
	"testing"

	"github.com/skrashevich/go-opus/pkg/oggreader"
)

func TestPionOggReader(t *testing.T) {
	// Two checksum-valid pages: OpusHead followed by a five-byte Opus packet.
	container := []byte{
		0x4f, 0x67, 0x67, 0x53, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x8e, 0x9b, 0x20, 0xaa, 0x00, 0x00,
		0x00, 0x00, 0x61, 0xee, 0x61, 0x17, 0x01, 0x13, 0x4f, 0x70,
		0x75, 0x73, 0x48, 0x65, 0x61, 0x64, 0x01, 0x02, 0x00, 0x0f,
		0x80, 0xbb, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4f, 0x67, 0x67,
		0x53, 0x00, 0x00, 0xda, 0x93, 0xc2, 0xd9, 0x00, 0x00, 0x00,
		0x00, 0x8e, 0x9b, 0x20, 0xaa, 0x02, 0x00, 0x00, 0x00, 0x49,
		0x97, 0x03, 0x37, 0x01, 0x05, 0x98, 0x36, 0xbe, 0x88, 0x9e,
	}
	r, h, err := oggreader.NewWith(bytes.NewReader(container))
	if err != nil {
		t.Fatal(err)
	}
	if h.Channels != 2 || h.SampleRate != 48000 || h.PreSkip != 3840 {
		t.Fatalf("header: %+v", h)
	}
	packet, page, err := r.ParseNextPacket()
	if err != nil || !bytes.Equal(packet, []byte{0x98, 0x36, 0xbe, 0x88, 0x9e}) || page.GranulePosition != 3653407706 {
		t.Fatalf("packet: %x %+v %v", packet, page, err)
	}
	if _, _, err := r.ParseNextPacket(); !errors.Is(err, io.EOF) {
		t.Fatalf("EOF: %v", err)
	}
	container[len(container)-1] ^= 1
	r, _, err = oggreader.NewWith(bytes.NewReader(container))
	if err != nil {
		t.Fatal(err)
	}
	if _, _, err := r.ParseNextPacket(); err == nil {
		t.Fatal("corrupt checksum accepted")
	}
}
